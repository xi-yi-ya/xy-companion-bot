const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('./runtime/browser/node_modules/playwright-core');
const fixture=JSON.parse(fs.readFileSync(path.join(__dirname,'runtime/qa/persona-live-input.json'),'utf8'));
const API='/api/v1/plugins/extensions/astrbot_plugin_companion_memory/';
(async()=>{
  const browser=await chromium.launch({executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',headless:true});
  const errors=[];
  try {
    const context=await browser.newContext({viewport:{width:1440,height:1100}});
    const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:6185/#/plugin-view/astrbot_plugin_companion_memory/memories',{waitUntil:'networkidle'});
    const frame=page.frames().find(f=>f!==page.mainFrame()&&f.url().includes('plugin'));
    await frame.waitForFunction(()=>document.getElementById('notice')?.textContent.includes('载入'));
    const close=page.getByRole('button',{name:'关闭',exact:true});if(await close.isVisible())await close.click();
    await frame.locator('#people').selectOption('webchat:owner');
    await frame.locator('[data-tab="approvals"]').click();
    const owner=frame.locator(`[data-proposal-id="${fixture.owner_request}"]`);
    await owner.getByRole('button',{name:'拒绝',exact:true}).click();
    await frame.getByRole('dialog').getByRole('button',{name:'确认执行',exact:true}).click();
    await frame.getByRole('status').filter({hasText:'已拒绝'}).waitFor();
    const rejected=(await (await context.request.get('http://127.0.0.1:6185'+API+'persona?person=webchat:owner')).json()).proposals.find(p=>p.id===fixture.owner_request);
    if(rejected.status!=='rejected')throw new Error('Owner test request not rejected');
    console.log('Real Bot L0 request displayed with diff and sources; UI rejection: PASS');
    await frame.locator('#people').selectOption(fixture.person);
    await frame.waitForFunction(id=>document.querySelector(`[data-proposal-id="${id}"]`),fixture.l1_proposal);
    const l1=frame.locator(`[data-proposal-id="${fixture.l1_proposal}"]`);
    await page.screenshot({path:path.join(__dirname,'runtime/qa/persona-approval-pending.png'),fullPage:true});
    await l1.getByRole('button',{name:'批准这项修改',exact:true}).click();
    const confirm=frame.getByRole('dialog');
    if(!(await confirm.innerText()).includes('确认授权这项修改'))throw new Error('Approval lacked a concrete confirmation');
    await confirm.getByRole('button',{name:'取消',exact:true}).click();
    const canceled=(await (await context.request.get('http://127.0.0.1:6185'+API+'persona?person='+encodeURIComponent(fixture.person))).json()).proposals.find(p=>p.id===fixture.l1_proposal);
    if(canceled.status!=='pending')throw new Error('Cancel accidentally applied the edit');
    await l1.getByRole('button',{name:'批准这项修改',exact:true}).click();
    await confirm.getByRole('button',{name:'确认执行',exact:true}).click();
    await frame.getByRole('status').filter({hasText:'已批准并执行'}).waitFor();
    await frame.locator('[data-tab="habits"]').click();
    await frame.locator('#habits').getByText('已生效 · 不衰减',{exact:false}).waitFor();
    await page.screenshot({path:path.join(__dirname,'runtime/qa/persona-habit-approved.png'),fullPage:true});
    await page.reload({waitUntil:'networkidle'});
    const reloaded=page.frames().find(f=>f!==page.mainFrame()&&f.url().includes('plugin'));
    await reloaded.waitForFunction(()=>document.getElementById('notice')?.textContent.includes('载入'));
    if(await close.isVisible())await close.click();
    await reloaded.locator('#people').selectOption(fixture.person);
    await reloaded.getByRole('status').filter({hasText:'已切换'}).waitFor();
    await reloaded.locator('[data-tab="habits"]').click();
    await reloaded.locator('#habits').getByText('已生效 · 不衰减',{exact:false}).waitFor();
    console.log('L1 diff -> explicit confirmation -> approval -> habit injected state -> reload persistence: PASS');
    if(errors.length)throw new Error(JSON.stringify(errors));
    console.log('Persona browser runtime errors: 0');
  } finally {await browser.close();}
})().catch(e=>{console.error(e.message);process.exitCode=1;});
